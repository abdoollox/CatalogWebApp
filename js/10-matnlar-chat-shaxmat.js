  function reasonText(code, result) {
    if (code === "checkmate") { code = "mate"; }
    var side = result === "win" ? "_win" : "_loss";
    var d = XT[lang] || XT.uz;
    if (d["r_" + code + side] !== undefined) { return d["r_" + code + side]; }
    if (d["r_" + code] !== undefined) { return d["r_" + code]; }
    return String(code || "");
  }

